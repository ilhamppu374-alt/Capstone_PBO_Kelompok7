    private void tblFasilitasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblFasilitasMouseClicked
        if (!klikAksi(tblFasilitas, evt)) {
            return;
        }
        int baris = tblFasilitas.rowAtPoint(evt.getPoint());
        String id = String.valueOf(tblFasilitas.getValueAt(baris, 0));
        String nama = String.valueOf(tblFasilitas.getValueAt(baris, 1));
        if (klikTautanPertama(tblFasilitas, evt)) {
            tampil("ubah");
            return;
        }
        // TODO backend: ganti kondisi ini dengan pengecekan "fasilitas punya riwayat laporan" dari database
        boolean punyaRiwayat = !"F005".equals(id);
        if (punyaRiwayat) {
            konfirmasi("Fasilitas tidak dapat dihapus", "Fasilitas ini memiliki riwayat laporan kerusakan sehingga tidak dapat dihapus.",
                    "Mengerti", new java.awt.Color(185, 28, 28), new java.awt.Color(37, 99, 235), false);
        } else if (konfirmasi("Hapus fasilitas?", "Fasilitas " + id + " - " + nama + " akan dihapus permanen. Tindakan ini tidak dapat dibatalkan.",
                "Hapus", java.awt.Color.BLACK, new java.awt.Color(220, 38, 38), true)) {
            // TODO backend: hapus fasilitas dengan ID id
        }
    }//GEN-LAST:event_tblFasilitasMouseClicked


