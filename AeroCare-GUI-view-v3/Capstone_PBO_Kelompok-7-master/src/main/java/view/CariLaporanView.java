    /** true jika klik berada pada kolom terakhir (Aksi) sebuah baris tabel. */
    private static boolean klikAksi(javax.swing.JTable t, java.awt.event.MouseEvent evt) {
        return t.rowAtPoint(evt.getPoint()) >= 0 && t.columnAtPoint(evt.getPoint()) == t.getColumnCount() - 1;
    }

    /** true jika klik berada di sisi kiri sel Aksi (tautan pertama, mis. "Ubah"). */
    private static boolean klikTautanPertama(javax.swing.JTable t, java.awt.event.MouseEvent evt) {
        java.awt.Rectangle r = t.getCellRect(t.rowAtPoint(evt.getPoint()), t.getColumnCount() - 1, false);
        return evt.getX() - r.x < 52;
    }

