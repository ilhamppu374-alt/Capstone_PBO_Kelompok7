    /** Berpindah halaman sesuai menu sidebar (0 = Dashboard). */
    private void pilihMenu(int indeks) {
        String kartu = "dashboard";
        switch (indeks) {
            case 1:
                kartu = "pengguna";
                penggunaView1.tampilkan("list");
                break;
            case 2:
                kartu = "fasilitas";
                fasilitasView1.tampilkan("list");
                break;
            case 3:
                kartu = "laporan";
                laporanView1.tampilkan("saya");
                break;
            case 4:
                kartu = "cari";
                cariLaporanView1.tampilkan("cari");
                break;
            default:
                break;
        }
        ((java.awt.CardLayout) pnlContent.getLayout()).show(pnlContent, kartu);
        javax.swing.JButton[] menu = {btnMenu1, btnMenu2, btnMenu3, btnMenu4, btnMenu5};
        java.awt.Color aksen = java.awt.Color.decode("#2563EB");
        for (int i = 0; i < menu.length; i++) {
            boolean aktif = (i == indeks);
            menu[i].setBackground(aktif ? aksen : new java.awt.Color(15, 23, 42));
            menu[i].setForeground(aktif ? java.awt.Color.WHITE : new java.awt.Color(203, 213, 225));
            menu[i].setFont(menu[i].getFont().deriveFont(aktif ? java.awt.Font.BOLD : java.awt.Font.PLAIN));
        }
        lblBreadcrumb.setText("AEROCARE  /  " + JUDUL[indeks]);
    }

