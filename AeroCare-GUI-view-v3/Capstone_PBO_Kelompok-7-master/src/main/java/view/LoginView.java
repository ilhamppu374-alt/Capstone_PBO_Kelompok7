    private void btnMasukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMasukActionPerformed
        if (txtUsername.getText().trim().isEmpty() || txtPassword.getPassword().length == 0) {
            lblError.setText("Username dan password wajib diisi.");
            lblError.setVisible(true);
            return;
        }
        lblError.setVisible(false);
        // SEMENTARA (demo tampilan): peran ditentukan dari username. Ganti dengan LoginController.login(...) dari backend.
        String user = txtUsername.getText().trim().toLowerCase();
        javax.swing.JFrame tujuan;
        if (user.startsWith("admin")) {
            tujuan = new DashboardAdmin();
        } else if (user.startsWith("supervisor")) {
            tujuan = new DashboardSupervisor();
        } else if (user.startsWith("petugas")) {
            tujuan = new DashboardPetugas();
        } else {
            lblError.setText("Login gagal: username/password salah atau akun nonaktif.");
            lblError.setVisible(true);
            return;
        }
        tujuan.setVisible(true);
        dispose();
    }//GEN-LAST:event_btnMasukActionPerformed

